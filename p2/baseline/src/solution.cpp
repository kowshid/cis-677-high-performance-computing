// src/solution.cpp -- YOURS, and the ONLY thing timed.
//
//     void hpcbench::solve(const Work& w, const Params& p, Result& out);
//
// Train the autoencoder n_genes -> 256 -> 32 -> 256 -> n_genes for ONE epoch,
// then write the trained parameters into out.W1, out.b1, ..., out.W4, out.b4
// (row-major [fan_in][fan_out], the same layout as the initial weights in p).
// The clock starts on entry and stops on return. Afterwards, off the clock, the
// harness computes the full-data reconstruction MSE of those parameters; that
// loss is what is checked. The initial weights and the batch order arrive in `p`,
// generated by the host from the seed; nothing about the model is yours to
// change. HOW it is computed is entirely yours.
//
// ---------------------------------------------------------------------------
// The whole computation, for one batch of B cells (B = 256, the last is 140):
//
//   forward      A1 = Xb W1 + b1     H1 = relu(A1)             B x 256
//                Z  = H1 W2 + b2                               B x 32
//                A3 = Z  W3 + b3     H3 = relu(A3)             B x 256
//                Xh = H3 W4 + b4                               B x n_genes
//   loss         L  = sum((Xh - Xb)^2) / (B * n_genes)
//   backward     dXh = 2 (Xh - Xb) / (B * n_genes)
//                dW4 = H3^T dXh    db4 = colsum(dXh)   dH3 = dXh W4^T
//                dA3 = dH3 * [A3 > 0]
//                dW3 = Z^T  dA3    db3 = colsum(dA3)   dZ  = dA3 W3^T
//                dW2 = H1^T dZ     db2 = colsum(dZ)    dH1 = dZ  W2^T
//                dA1 = dH1 * [A1 > 0]
//                dW1 = Xb^T dA1    db1 = colsum(dA1)
//   Adam, step t = 1, 2, ... (one per batch), for every parameter w with
//   gradient g:
//                m = beta1 m + (1 - beta1) g
//                v = beta2 v + (1 - beta2) g^2
//                w = w - lr * (m / (1 - beta1^t)) / (sqrt(v / (1 - beta2^t)) + eps)
//
// After the last step: copy every trained parameter into `out`.
// ---------------------------------------------------------------------------
//
// The baseline is correct and deliberately naive. Among other things it:
//   * keeps Adam's state as an ARRAY OF STRUCTS {w, m, v}          (LAY-1)
//   * allocates every activation and gradient buffer per batch    (ALO-2)
//   * multiplies by X as if it were dense, 94% zeros included
//   * forms dW1 = Xb^T dA1 in the textbook loop order, which walks both
//     operands down their columns
//   * runs on one thread
// Build it with -DHPCBENCH_GRADCHECK to finite-difference check the backward
// pass before training (see include/gradcheck.hpp). Keep that check passing
// as you change things.
#include "task.hpp"

#ifdef HPCBENCH_GRADCHECK
#include "gradcheck.hpp"
#endif

#include <cmath>
#include <cstdint>
#include <cstdio>
#include <vector>

namespace {

// One parameter and its two Adam moments, side by side.
struct AdamParam {
  double w;
  double m;
  double v;
};

struct Layer {
  std::uint64_t in = 0;
  std::uint64_t out = 0;
  std::vector<AdamParam> W;  // in x out, row-major
  std::vector<AdamParam> b;  // out
};

Layer make_layer(const double* W, const double* b, std::uint64_t in, std::uint64_t out) {
  Layer L;
  L.in = in;
  L.out = out;
  for (std::uint64_t i = 0; i < in * out; ++i) L.W.push_back(AdamParam{W[i], 0.0, 0.0});
  for (std::uint64_t j = 0; j < out; ++j) L.b.push_back(AdamParam{b[j], 0.0, 0.0});
  return L;
}

struct Model {
  Layer l1, l2, l3, l4;
};

struct Grads {
  std::vector<double> W1, b1, W2, b2, W3, b3, W4, b4;
};

// C = A * W + b, with A rows x in and C rows x out.
void affine(const double* A, std::uint64_t rows, const Layer& L, double* C) {
  for (std::uint64_t i = 0; i < rows; ++i)
    for (std::uint64_t j = 0; j < L.out; ++j) C[i * L.out + j] = L.b[j].w;
  for (std::uint64_t i = 0; i < rows; ++i)
    for (std::uint64_t k = 0; k < L.in; ++k) {
      const double a = A[i * L.in + k];
      for (std::uint64_t j = 0; j < L.out; ++j) C[i * L.out + j] += a * L.W[k * L.out + j].w;
    }
}

void relu(const double* A, double* H, std::uint64_t n) {
  for (std::uint64_t e = 0; e < n; ++e) H[e] = A[e] > 0.0 ? A[e] : 0.0;
}

// gW = A^T dC (in x out) and gb = colsum(dC), for A rows x in, dC rows x out.
void weight_grad(const double* A, const double* dC, std::uint64_t rows, std::uint64_t in,
                 std::uint64_t out, std::vector<double>& gW, std::vector<double>& gb) {
  gW.assign(in * out, 0.0);
  gb.assign(out, 0.0);
  for (std::uint64_t i = 0; i < rows; ++i)
    for (std::uint64_t k = 0; k < in; ++k) {
      const double a = A[i * in + k];
      for (std::uint64_t j = 0; j < out; ++j) gW[k * out + j] += a * dC[i * out + j];
    }
  for (std::uint64_t i = 0; i < rows; ++i)
    for (std::uint64_t j = 0; j < out; ++j) gb[j] += dC[i * out + j];
}

// dA = dC W^T (rows x in), for dC rows x out.
void input_grad(const double* dC, std::uint64_t rows, const Layer& L, double* dA) {
  for (std::uint64_t i = 0; i < rows; ++i)
    for (std::uint64_t k = 0; k < L.in; ++k) {
      double s = 0.0;
      for (std::uint64_t j = 0; j < L.out; ++j) s += dC[i * L.out + j] * L.W[k * L.out + j].w;
      dA[i * L.in + k] = s;
    }
}

// Forward pass on one batch and, when `g` is given, the backward pass too.
// Returns the batch loss.
double batch_pass(const Model& M, const double* Xb, std::uint64_t B, std::uint64_t D, Grads* g) {
  const std::uint64_t H = M.l1.out, K = M.l2.out;

  // Every buffer, fresh for every batch.
  std::vector<double> A1(B * H), H1(B * H), Z(B * K), A3(B * H), H3(B * H), Xh(B * D);
  affine(Xb, B, M.l1, A1.data());
  relu(A1.data(), H1.data(), B * H);
  affine(H1.data(), B, M.l2, Z.data());
  affine(Z.data(), B, M.l3, A3.data());
  relu(A3.data(), H3.data(), B * H);
  affine(H3.data(), B, M.l4, Xh.data());

  const double scale = 1.0 / (double(B) * double(D));
  std::vector<double> dXh(B * D);
  double loss = 0.0;
  for (std::uint64_t e = 0; e < B * D; ++e) {
    const double d = Xh[e] - Xb[e];
    loss += d * d;
    dXh[e] = 2.0 * scale * d;
  }
  loss *= scale;
  if (!g) return loss;

  // Layer 4.
  weight_grad(H3.data(), dXh.data(), B, H, D, g->W4, g->b4);
  std::vector<double> dA3(B * H);
  input_grad(dXh.data(), B, M.l4, dA3.data());
  for (std::uint64_t e = 0; e < B * H; ++e)
    if (!(A3[e] > 0.0)) dA3[e] = 0.0;

  // Layer 3.
  weight_grad(Z.data(), dA3.data(), B, K, H, g->W3, g->b3);
  std::vector<double> dZ(B * K);
  input_grad(dA3.data(), B, M.l3, dZ.data());

  // Layer 2.
  weight_grad(H1.data(), dZ.data(), B, H, K, g->W2, g->b2);
  std::vector<double> dA1(B * H);
  input_grad(dZ.data(), B, M.l2, dA1.data());
  for (std::uint64_t e = 0; e < B * H; ++e)
    if (!(A1[e] > 0.0)) dA1[e] = 0.0;

  // Layer 1: dW1[c][j] = sum_i Xb[i][c] * dA1[i][j], straight from the
  // definition. The innermost loop strides down a column of both operands.
  g->W1.assign(D * H, 0.0);
  g->b1.assign(H, 0.0);
  for (std::uint64_t c = 0; c < D; ++c)
    for (std::uint64_t j = 0; j < H; ++j) {
      double s = 0.0;
      for (std::uint64_t i = 0; i < B; ++i) s += Xb[i * D + c] * dA1[i * H + j];
      g->W1[c * H + j] = s;
    }
  for (std::uint64_t i = 0; i < B; ++i)
    for (std::uint64_t j = 0; j < H; ++j) g->b1[j] += dA1[i * H + j];
  return loss;
}

void adam(std::vector<AdamParam>& P, const std::vector<double>& G, const hpcbench::Params& p,
          double bc1, double bc2) {
  for (std::uint64_t i = 0; i < P.size(); ++i) {
    AdamParam& q = P[i];
    const double g = G[i];
    q.m = p.beta1 * q.m + (1.0 - p.beta1) * g;
    q.v = p.beta2 * q.v + (1.0 - p.beta2) * g * g;
    const double mhat = q.m / bc1;
    const double vhat = q.v / bc2;
    q.w -= p.lr * mhat / (std::sqrt(vhat) + p.eps);
  }
}

#ifdef HPCBENCH_GRADCHECK
void check_layer(const char* wname, const char* bname, Layer& L, const std::vector<double>& gW,
                 const std::vector<double>& gb, const Model& M, const double* Xb,
                 std::uint64_t B, std::uint64_t D, hpcbench::GradCheckReport& total) {
  auto loss = [&]() { return batch_pass(M, Xb, B, D, nullptr); };
  for (int which = 0; which < 2; ++which) {
    std::vector<AdamParam>& P = which == 0 ? L.W : L.b;
    const std::vector<double>& G = which == 0 ? gW : gb;
    const hpcbench::GradCheckReport r = hpcbench::gradcheck(
        which == 0 ? wname : bname, P.size(), G.data(),
        [&](std::size_t i) { return P[i].w; }, [&](std::size_t i, double v) { P[i].w = v; },
        loss);
    total.checked += r.checked;
    total.failed += r.failed;
    if (r.max_rel_err > total.max_rel_err) total.max_rel_err = r.max_rel_err;
  }
}
#endif

}  // namespace

void hpcbench::solve(const Work& w, const Params& p, Result& out) {
  // On the clock: the baseline pays to read 296 MB of dense doubles.
  Reader r = w.open("X.bin");
  const std::uint64_t n_cells = r.read_value<std::uint64_t>();
  const std::uint64_t D = r.read_value<std::uint64_t>();
  std::vector<double> X(static_cast<std::size_t>(n_cells * D));
  r.read(X.data(), X.size() * sizeof(double));
  r.close();

  const std::uint64_t H = p.hidden, K = p.latent;
  Model M;
  M.l1 = make_layer(p.W1, p.b1, D, H);
  M.l2 = make_layer(p.W2, p.b2, H, K);
  M.l3 = make_layer(p.W3, p.b3, K, H);
  M.l4 = make_layer(p.W4, p.b4, H, D);

  double beta1_t = 1.0, beta2_t = 1.0, loss_sum = 0.0;
  std::uint64_t steps = 0;
  for (std::uint64_t start = 0; start < n_cells; start += p.batch) {
    const std::uint64_t B = start + p.batch <= n_cells ? p.batch : n_cells - start;

    // Gather this batch's rows, in the host's order.
    std::vector<double> Xb(B * D);
    for (std::uint64_t i = 0; i < B; ++i) {
      const std::uint64_t cell = p.order[start + i];
      for (std::uint64_t c = 0; c < D; ++c) Xb[i * D + c] = X[cell * D + c];
    }

    Grads g;
    loss_sum += batch_pass(M, Xb.data(), B, D, &g);

#ifdef HPCBENCH_GRADCHECK
    if (steps == 0) {
      hpcbench::GradCheckReport total;
      check_layer("W1", "b1", M.l1, g.W1, g.b1, M, Xb.data(), B, D, total);
      check_layer("W2", "b2", M.l2, g.W2, g.b2, M, Xb.data(), B, D, total);
      check_layer("W3", "b3", M.l3, g.W3, g.b3, M, Xb.data(), B, D, total);
      check_layer("W4", "b4", M.l4, g.W4, g.b4, M, Xb.data(), B, D, total);
      std::fprintf(stderr, "gradcheck: %zu weights checked, %zu mismatched, max rel err %.2e\n",
                   total.checked, total.failed, total.max_rel_err);
    }
#endif

    ++steps;
    beta1_t *= p.beta1;
    beta2_t *= p.beta2;
    const double bc1 = 1.0 - beta1_t, bc2 = 1.0 - beta2_t;
    adam(M.l1.W, g.W1, p, bc1, bc2);
    adam(M.l1.b, g.b1, p, bc1, bc2);
    adam(M.l2.W, g.W2, p, bc1, bc2);
    adam(M.l2.b, g.b2, p, bc1, bc2);
    adam(M.l3.W, g.W3, p, bc1, bc2);
    adam(M.l3.b, g.b3, p, bc1, bc2);
    adam(M.l4.W, g.W4, p, bc1, bc2);
    adam(M.l4.b, g.b4, p, bc1, bc2);
  }
  std::fprintf(stderr, "epoch: %llu steps, mean batch loss %.9f\n", (unsigned long long)steps,
               loss_sum / double(steps));

  // The answer: the trained parameters, back in the host's layout.
  auto put = [](const std::vector<AdamParam>& P, double* dst) {
    for (std::uint64_t i = 0; i < P.size(); ++i) dst[i] = P[i].w;
  };
  put(M.l1.W, out.W1);
  put(M.l1.b, out.b1);
  put(M.l2.W, out.W2);
  put(M.l2.b, out.b2);
  put(M.l3.W, out.W3);
  put(M.l3.b, out.b3);
  put(M.l4.W, out.W4);
  put(M.l4.b, out.b4);
}
